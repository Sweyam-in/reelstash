package httpapi

import "github.com/go-chi/chi/v5"

// mountCatalog registers people, studios, series, categories, tags, and playlists.
func (a *API) mountCatalog(r chi.Router) {
	r.Route("/performers", func(r chi.Router) {
		admin := r.With(a.requireAdmin)
		r.Get("/", a.listPerformers)
		admin.Post("/", a.createPerformer)
		admin.Get("/jobs/{jobId}", a.getPerformerMatchJob)
		admin.Get("/duplicates", a.listPerformerDuplicates)
		admin.Post("/duplicates/dismiss", a.dismissPerformerDuplicate)
		r.Get("/{id}/image", a.servePerformerImage)
		admin.Post("/{id}/image", a.uploadPerformerImage)
		admin.Delete("/{id}/image", a.deletePerformerImage)
		admin.Get("/{id}/field-sources", a.performerFieldSources)
		admin.Put("/{id}/field-sources", a.setPerformerFieldSources)
		admin.Get("/{id}/photos", a.listPerformerPhotos)
		admin.Post("/{id}/photos/fetch", a.fetchPerformerPhotos)
		r.Get("/{id}/photos/{photoId}", a.servePerformerImage)
		admin.Put("/{id}/photos/{photoId}/primary", a.choosePerformerPhoto)
		admin.Delete("/{id}/photos/{photoId}", a.deletePerformerPhoto)
		r.Put("/{id}/favorite", a.setPerformerFavorite)
		admin.Post("/{id}/merge", a.mergePerformer)
		r.Get("/{id}/related", a.relatedPerformers)
		admin.Get("/{id}/media", a.listPerformerMedia)
		admin.Post("/{id}/media", a.linkPerformerMedia)
		admin.Delete("/{id}/media/{mediaItemId}", a.unlinkPerformerMedia)
		admin.Get("/{id}/match", a.searchPerformerProviders)
		admin.Post("/{id}/match", a.matchPerformerProvider)
		admin.Post("/{id}/match/unmatch", a.unmatchPerformer)
		r.Get("/{id}", a.getPerformer)
		admin.Put("/{id}", a.updatePerformer)
		admin.Delete("/{id}", a.deletePerformer)
	})
	r.Route("/studios", func(r chi.Router) {
		admin := r.With(a.requireAdmin)
		r.Get("/", a.listStudios)
		admin.Post("/", a.createStudio)
		admin.Get("/jobs/{jobId}", a.getStudioMatchJob)
		r.Get("/{id}/image", a.serveStudioImage)
		admin.Post("/{id}/image", a.uploadStudioImage)
		admin.Delete("/{id}/image", a.deleteStudioImage)
		admin.Get("/{id}/match", a.searchStudioProviders)
		admin.Post("/{id}/match", a.matchStudioProvider)
		admin.Post("/{id}/match/unmatch", a.unmatchStudio)
		admin.Get("/{id}/duplicates", a.listStudioDuplicates)
		admin.Post("/{id}/merge", a.mergeStudio)
		admin.Post("/{id}/media", a.linkStudioMedia)
		admin.Delete("/{id}/media/{mediaItemId}", a.unlinkStudioMedia)
		r.Get("/{id}", a.getStudio)
		admin.Put("/{id}", a.updateStudio)
		admin.Delete("/{id}", a.deleteStudio)
	})
	r.Route("/series", func(r chi.Router) {
		admin := r.With(a.requireAdmin)
		r.Get("/", a.listSeries)
		admin.Post("/", a.createSeries)
		r.Get("/{id}", a.getSeries)
		r.Get("/{id}/image", a.serveSeriesImage)
		admin.Post("/{id}/image", a.uploadSeriesImage)
		admin.Post("/{id}/image/provider", a.useSeriesProviderImage)
		admin.Delete("/{id}/image", a.deleteSeriesImage)
		r.Get("/{id}/backdrop", a.serveSeriesBackdrop)
		admin.Post("/{id}/backdrop", a.uploadSeriesBackdrop)
		admin.Delete("/{id}/backdrop", a.deleteSeriesBackdrop)
		admin.Post("/{id}/media", a.addSeriesMedia)
		admin.Put("/{id}/media/order", a.orderSeriesMedia)
		admin.Delete("/{id}/media/{mediaItemId}", a.removeSeriesMedia)
		admin.Get("/{id}/providers", a.searchSeriesProviders)
		admin.Post("/{id}/providers", a.linkSeriesProvider)
		admin.Delete("/{id}/providers/{provider}", a.unlinkSeriesProvider)
		admin.Get("/{id}/parts", a.listSeriesParts)
		admin.Post("/{id}/parts/assign", a.assignSeriesPart)
		admin.Put("/{id}", a.updateSeries)
		admin.Delete("/{id}", a.deleteSeries)
	})
	r.Route("/categories", func(r chi.Router) {
		admin := r.With(a.requireAdmin)
		r.Get("/", a.listCategories)
		admin.Post("/", a.createCategory)
		admin.Put("/{id}", a.updateCategory)
		admin.Delete("/{id}", a.deleteCategory)
	})
	r.Route("/tags", func(r chi.Router) {
		r.Get("/", a.listTags)
		r.With(a.requireAdmin).Post("/", a.createTag)
	})
	// Playlists are private: only their owner can see or change one.
	r.Route("/collections", func(r chi.Router) {
		r.Get("/", a.listCollections)
		r.Post("/", a.createCollection)
		r.Route("/{id}", func(r chi.Router) {
			r.Use(a.requireOwnCollection)
			r.Get("/", a.getCollection)
			r.Patch("/", a.updateCollection)
			r.Delete("/", a.deleteCollection)
			r.Post("/items", a.addCollectionItem)
			r.Delete("/items/{mediaItemID}", a.removeCollectionItem)
			r.Post("/items/{mediaItemID}/move", a.moveCollectionItem)
		})
	})
}
