package httpapi

import "github.com/go-chi/chi/v5"

// mountAdmin registers the admin-only routes.
func (a *API) mountAdmin(r chi.Router) {
	r.Route("/admin", func(r chi.Router) {
		r.Use(a.requireAdmin)
		r.Use(a.auditAdmin)

		r.Get("/audit", a.listAuditEvents)

		r.Get("/overview", a.adminOverview)
		r.Get("/analytics", a.adminAnalytics)
		r.Get("/analytics/usage", a.adminUsage)
		r.Get("/health", a.adminHealth)
		r.Get("/providers", a.adminProviders)
		r.Put("/providers/order", a.updateProviderOrder)
		r.Put("/providers/{id}/config", a.updateProviderConfig)
		r.Delete("/providers/{id}/config", a.deleteProviderConfig)
		r.Post("/providers/{id}/test", a.testProvider)
		r.Post("/providers/recover-links", a.startLinkRecovery)
		r.Get("/subtitle-provider", a.adminSubtitleProvider)
		r.Put("/subtitle-provider", a.updateSubtitleProvider)
		r.Delete("/subtitle-provider", a.deleteSubtitleProvider)
		r.Post("/subtitle-provider/test", a.testSubtitleProvider)
		r.Post("/providers/external", a.addExternalProvider)
		r.Post("/providers/external/{id}/refresh", a.refreshExternalProvider)
		r.Put("/providers/external/{id}/enabled", a.setExternalProviderEnabled)
		r.Get("/providers/external/{id}/log", a.externalProviderLog)
		r.Delete("/providers/external/{id}/log", a.clearExternalProviderLog)
		r.Delete("/providers/external/{id}", a.removeExternalProvider)
		r.Route("/plugins", func(r chi.Router) {
			r.Get("/", a.listPlugins)
			r.Post("/install", a.installPluginUpload)
			r.Post("/install-url", a.installPluginURL)
			r.Put("/{id}/enabled", a.setPluginEnabled)
			r.Put("/{id}/config", a.updatePluginConfig)
			r.Post("/{id}/restart", a.restartPlugin)
			r.Put("/{id}/update-source", a.setPluginUpdateSource)
			r.Post("/{id}/check-update", a.checkPluginUpdate)
			r.Post("/{id}/update", a.updatePlugin)
			r.Get("/{id}/log", a.pluginLog)
			r.Delete("/{id}", a.removePlugin)
		})
		r.Get("/auth", a.getAuthSettings)
		r.Put("/auth", a.updateAuthSettings)
		r.Route("/users", func(r chi.Router) {
			r.Get("/", a.listUsers)
			r.Post("/", a.createUser)
			r.Get("/{id}", a.getUser)
			r.Put("/{id}", a.updateUser)
			r.Delete("/{id}", a.deleteUser)
			r.Get("/{id}/sessions", a.listUserSessions)
			r.Delete("/{id}/sessions", a.revokeUserSessions)
			r.Delete("/{id}/sessions/{sessionID}", a.revokeUserSessions)
			r.Put("/{id}/password", a.resetUserPassword)
			r.Put("/{id}/libraries", a.setUserLibraries)
		})
		r.Route("/libraries", func(r chi.Router) {
			r.Get("/", a.listLibraries)
			r.Post("/", a.createLibrary)
			r.Put("/order", a.reorderLibraries)
			r.Put("/{id}", a.updateLibrary)
			r.Delete("/{id}", a.deleteLibrary)
			r.Post("/{id}/scan", a.startLibraryScan)
			r.Post("/{id}/scan/cancel", a.cancelLibraryScan)
		})

		r.Route("/storage", func(r chi.Router) {
			r.Get("/", a.listStorageLocations)
			r.Post("/", a.createStorageLocation)
			r.Put("/{id}", a.updateStorageLocation)
			r.Delete("/{id}", a.deleteStorageLocation)
			r.Get("/{id}/insights", a.storageLocationInsights)
		})
		r.Route("/scan-rules", func(r chi.Router) {
			r.Get("/", a.listScanRules)
			r.Post("/", a.createScanRule)
			r.Post("/test", a.testScanRule)
			r.Delete("/{id}", a.deleteScanRule)
		})
		r.Route("/setup", func(r chi.Router) {
			r.Get("/", a.getSetupStatus)
			r.Post("/check-path", a.checkSetupPath)
			r.Post("/complete", a.completeSetup)
		})
		r.Get("/appearance", a.getAppearance)
		r.Put("/appearance", a.updateAppearance)
		r.Get("/automation", a.getAutomation)
		r.Route("/schedules", func(r chi.Router) {
			r.Post("/", a.createSchedule)
			r.Put("/{id}", a.updateSchedule)
			r.Delete("/{id}", a.deleteSchedule)
		})
		r.Put("/libraries/{id}/watch", a.setLibraryWatch)
		r.Route("/webhooks", func(r chi.Router) {
			r.Get("/", a.listWebhooks)
			r.Post("/", a.createWebhook)
			r.Put("/{id}", a.updateWebhook)
			r.Delete("/{id}", a.deleteWebhook)
			r.Post("/{id}/test", a.testWebhook)
			r.Get("/{id}/deliveries", a.listWebhookDeliveries)
		})
		r.Put("/tags/{id}", a.updateTag)
		r.Delete("/tags/{id}", a.deleteTag)
		r.Get("/videos", a.listAdminVideos)
		r.Post("/videos/match", a.matchAdminVideos)
		r.Post("/videos/confirm", a.confirmAdminVideos)
		r.Delete("/media/{id}", a.deleteMediaItem)
		r.Route("/organizer", func(r chi.Router) {
			r.Route("/{libraryID}", func(r chi.Router) {
				r.Get("/rules", a.listOrganizerRules)
				r.Post("/rules", a.createOrganizerRule)
				r.Put("/rules/order", a.reorderOrganizerRules)
				r.Put("/rules/{id}", a.updateOrganizerRule)
				r.Delete("/rules/{id}", a.deleteOrganizerRule)
				r.Get("/settings", a.getOrganizerSettings)
				r.Put("/settings", a.updateOrganizerSettings)
				r.Get("/preview", a.previewOrganizer)
				r.Post("/run", a.runOrganizer)
				r.Get("/cleanup", a.previewCleanup)
				r.Post("/cleanup", a.runCleanup)
			})
		})
		r.Route("/files", func(r chi.Router) {
			r.Put("/", a.renameFileEntry)
			r.Put("/nfo", a.saveFileNFO)
			r.Delete("/", a.deleteFileEntry)
			r.Post("/dir", a.createFileDir)
			r.Post("/move", a.moveFileEntry)
			r.Post("/copy", a.copyFileEntry)
			r.Post("/transfer", a.startFileTransfer)
			r.Post("/upload", a.uploadFiles)
		})
		r.Route("/duplicates", func(r chi.Router) {
			r.Get("/scan", a.duplicateScanStatus)
			r.Post("/scan", a.startDuplicateScan)
			r.Post("/scan/cancel", a.cancelDuplicateScan)
		})
		r.Route("/scans", func(r chi.Router) {
			r.Get("/", a.listScanJobs)
			r.Post("/{storageLocationID}", a.startScan)
			r.Post("/{storageLocationID}/cancel", a.cancelScan)
		})
		r.Route("/housekeeping", func(r chi.Router) {
			r.Get("/", a.getHousekeeping)
			r.Put("/settings", a.updateHousekeepingSettings)
			r.Post("/run", a.runHousekeeping)
		})
		r.Route("/jobs", func(r chi.Router) {
			r.Get("/", a.listBackgroundJobs)
			r.Post("/run", a.runBackgroundJob)
			r.Delete("/finished", a.clearFinishedJobs)
			r.Get("/{id}", a.getBackgroundJob)
			r.Post("/{id}/cancel", a.cancelBackgroundJob)
			r.Post("/{id}/retry", a.retryBackgroundJob)
		})
		r.Route("/rename", func(r chi.Router) {
			r.Get("/", a.listRenameQueue)
			r.Get("/preview/{mediaFileID}", a.previewRename)
			r.Post("/{mediaFileID}", a.applyRename)
		})
		r.Route("/review", func(r chi.Router) {
			r.Get("/", a.listReviewQueue)
			r.Get("/matches", a.listMatchSuggestions)
			r.Post("/matches/{mediaItemID}/dismiss", a.dismissMatchSuggestion)
			r.Post("/{mediaItemID}/confirm", a.confirmReview)
		})
		r.Route("/namer", func(r chi.Router) {
			r.Post("/match/{mediaFileID}", a.namerMatch)
			r.Post("/select/{mediaFileID}", a.namerSelectCandidate)
		})
		r.Get("/performers/empty", a.countEmptyPerformers)
		r.Post("/performers/cleanup", a.cleanupPerformers)
		r.Get("/categories/empty", a.countEmptyCategories)
		r.Post("/categories/cleanup", a.cleanupCategories)
		r.Get("/performers/sync", a.performerSyncStatus)
		r.Post("/performers/sync", a.startPerformerSync)
		r.Get("/studios/sync", a.studioSyncStatus)
		r.Post("/studios/sync", a.startStudioSync)
	})
}
